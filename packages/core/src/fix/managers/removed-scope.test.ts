import { describe, expect, it } from 'vitest';
import { assertLockScope, type LockGraph, type Targets } from './lock-guard.js';
import { npmGraph } from './npm-lock.js';
import { pnpmGraph, yarnGraph } from './text-lock.js';

// A repository on ioredis 4 with @types/ioredis at the root, and @types/node reached only
// through it. The plan moves ioredis 4.28.5 → 5.4.1 and removes @types/ioredis, whose last
// release is a deprecated stub: ioredis 5 ships its own types (check/removed.ts).
interface State {
  ioredis: string;
  /** Absent once removed. */
  types?: string;
  other?: string;
}
const nodeTypes = '20.0.0';
const npm = ({ ioredis, types, other = '1.0.0' }: State) =>
  JSON.stringify({
    lockfileVersion: 3,
    packages: {
      '': {
        dependencies: { ioredis: '^4.28.5', other: '^1.0.0' },
        devDependencies: types ? { '@types/ioredis': '^4.28.10' } : {},
      },
      'node_modules/ioredis': { version: ioredis, integrity: `sha512-ioredis-${ioredis}` },
      'node_modules/other': { version: other, integrity: `sha512-other-${other}` },
      ...(types
        ? {
            'node_modules/@types/ioredis': {
              version: types,
              integrity: `sha512-types-${types}`,
              dev: true,
              dependencies: types.startsWith('4') ? { '@types/node': '*' } : { ioredis: '*' },
            },
            ...(types.startsWith('4')
              ? {
                  'node_modules/@types/node': {
                    version: nodeTypes,
                    integrity: `sha512-node-${nodeTypes}`,
                    dev: true,
                  },
                }
              : {}),
          }
        : {}),
    },
  });
const pnpm = ({ ioredis, types, other = '1.0.0' }: State) => `lockfileVersion: '9.0'

settings:
  autoInstallPeers: true
  excludeLinksFromLockfile: false

importers:

  .:
    dependencies:
      ioredis:
        specifier: ^4.28.5
        version: ${ioredis}
      other:
        specifier: ^1.0.0
        version: ${other}
${
  types
    ? `    devDependencies:
      '@types/ioredis':
        specifier: ^4.28.10
        version: ${types}
`
    : ''
}
packages:
${
  types
    ? `
  '@types/ioredis@${types}':
    resolution: {integrity: sha512-types-${types}}
${
  types.startsWith('4')
    ? `
  '@types/node@${nodeTypes}':
    resolution: {integrity: sha512-node-${nodeTypes}}
`
    : ''
}`
    : ''
}
  ioredis@${ioredis}:
    resolution: {integrity: sha512-ioredis-${ioredis}}

  other@${other}:
    resolution: {integrity: sha512-other-${other}}

snapshots:
${
  types
    ? `
  '@types/ioredis@${types}':
    dependencies:
${types.startsWith('4') ? `      '@types/node': ${nodeTypes}` : `      ioredis: ${ioredis}`}
${types.startsWith('4') ? `\n  '@types/node@${nodeTypes}': {}\n` : ''}`
    : ''
}
  ioredis@${ioredis}: {}

  other@${other}: {}
`;
const yarn = ({
  ioredis,
  types,
  other = '1.0.0',
}: State) => `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

${
  types
    ? `
"@types/ioredis@^4.28.10":
  version "${types}"
  resolved "https://registry.yarnpkg.com/@types/ioredis/-/ioredis-${types}.tgz"
  integrity sha512-types-${types}
  dependencies:
    ${types.startsWith('4') ? '"@types/node" "*"' : 'ioredis "*"'}
${
  types.startsWith('4')
    ? `
"@types/node@*":
  version "${nodeTypes}"
  resolved "https://registry.yarnpkg.com/@types/node/-/node-${nodeTypes}.tgz"
  integrity sha512-node-${nodeTypes}
`
    : ''
}`
    : ''
}
ioredis@^4.28.5:
  version "${ioredis}"
  resolved "https://registry.yarnpkg.com/ioredis/-/ioredis-${ioredis}.tgz"
  integrity sha512-ioredis-${ioredis}

other@^1.0.0:
  version "${other}"
  resolved "https://registry.yarnpkg.com/other/-/other-${other}.tgz"
  integrity sha512-other-${other}
`;

const managers: [string, (text: string, target: Targets) => LockGraph, (s: State) => string][] = [
  ['npm', npmGraph, npm],
  ['pnpm', pnpmGraph, pnpm],
  ['yarn', yarnGraph, yarn],
];
const before: State = { ioredis: '4.28.5', types: '4.28.10' };
const removed = ['@types/ioredis'];

describe.each(managers)(
  '%s: the install scope guard and a removed @types stub',
  (_, graph, lock) => {
    // As upgradeInstall builds them: the removed stub is among the graphs' targets, not the moves.
    const guard = (after: State, remove: readonly string[]) =>
      assertLockScope(
        graph(lock(before), ['ioredis', ...remove]),
        graph(lock(after), ['ioredis', ...remove]),
        'ioredis',
        [],
        remove,
      );

    it('allows the planned removal, and what only the stub reached going with it', () => {
      const diff = guard({ ioredis: '5.4.1' }, removed);
      expect(diff.removed.some((k) => k.includes('@types/ioredis'))).toBe(true);
      expect(diff.removed.some((k) => k.includes('@types/node'))).toBe(true);
    });

    it('refuses the removal when the plan did not make it', () => {
      expect(() => guard({ ioredis: '5.4.1' }, [])).toThrow(/outside ioredis's dependency subtree/);
    });

    it('refuses the stub moving to its deprecated release instead of going', () => {
      expect(() => guard({ ioredis: '5.4.1', types: '5.0.0' }, removed)).toThrow(
        /outside ioredis's dependency subtree/,
      );
    });

    it('still refuses anything else that moves next to the removal', () => {
      expect(() => guard({ ioredis: '5.4.1', other: '1.1.0' }, removed)).toThrow(
        /outside ioredis's dependency subtree/,
      );
    });
  },
);
