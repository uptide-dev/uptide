import { describe, expect, it } from 'vitest';
import { assertLockScope, type LockGraph, type Targets } from './lock-guard.js';
import { npmGraph } from './npm-lock.js';
import { pnpmGraph, yarnGraph } from './text-lock.js';

// batch-ai's shape: openai and zod declared at the root, zod an optional peer of openai.
// The plan moves openai 4.83.0 → 7.4.0 and zod 3.24.2 → 3.25.0 because openai 7 requires it.
interface Versions {
  openai: string;
  zod: string;
  other?: string;
}
const npm = ({ openai, zod, other = '1.0.0' }: Versions) =>
  JSON.stringify({
    lockfileVersion: 3,
    packages: {
      '': { dependencies: { openai: '^4.83.0', other: '^1.0.0', zod: '^3.24.1' } },
      'node_modules/openai': {
        version: openai,
        integrity: `sha512-openai-${openai}`,
        peerDependencies: { zod: openai.startsWith('7') ? '^3.25 || ^4.0' : '^3.23.8' },
        peerDependenciesMeta: { zod: { optional: true } },
      },
      'node_modules/other': { version: other, integrity: `sha512-other-${other}` },
      'node_modules/zod': { version: zod, integrity: `sha512-zod-${zod}` },
    },
  });
const pnpm = ({ openai, zod, other = '1.0.0' }: Versions) => `lockfileVersion: '9.0'

settings:
  autoInstallPeers: true
  excludeLinksFromLockfile: false

importers:

  .:
    dependencies:
      openai:
        specifier: ^4.83.0
        version: ${openai}(zod@${zod})
      other:
        specifier: ^1.0.0
        version: ${other}
      zod:
        specifier: ^3.24.1
        version: ${zod}

packages:

  openai@${openai}:
    resolution: {integrity: sha512-openai-${openai}}
    peerDependencies:
      zod: ${openai.startsWith('7') ? "'^3.25 || ^4.0'" : '^3.23.8'}
    peerDependenciesMeta:
      zod:
        optional: true

  other@${other}:
    resolution: {integrity: sha512-other-${other}}

  zod@${zod}:
    resolution: {integrity: sha512-zod-${zod}}

snapshots:

  openai@${openai}(zod@${zod}):
    optionalDependencies:
      zod: ${zod}

  other@${other}: {}

  zod@${zod}: {}
`;
const yarn = ({
  openai,
  zod,
  other = '1.0.0',
}: Versions) => `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


openai@^4.83.0:
  version "${openai}"
  resolved "https://registry.yarnpkg.com/openai/-/openai-${openai}.tgz"
  integrity sha512-openai-${openai}

other@^1.0.0:
  version "${other}"
  resolved "https://registry.yarnpkg.com/other/-/other-${other}.tgz"
  integrity sha512-other-${other}

zod@^3.24.1:
  version "${zod}"
  resolved "https://registry.yarnpkg.com/zod/-/zod-${zod}.tgz"
  integrity sha512-zod-${zod}
`;

const managers: [string, (text: string, target: Targets) => LockGraph, (v: Versions) => string][] =
  [
    ['npm', npmGraph, npm],
    ['pnpm', pnpmGraph, pnpm],
    ['yarn', yarnGraph, yarn],
  ];
const before = { openai: '4.83.0', zod: '3.24.2' };
const planned = ['openai', 'zod'];

describe.each(managers)('%s: the install scope guard and required moves', (_, graph, lock) => {
  const guard = (after: Versions, targets: Targets) =>
    assertLockScope(graph(lock(before), targets), graph(lock(after), targets), targets);

  it('allows the lead and the package its target requires to move together', () => {
    expect(() => guard({ openai: '7.4.0', zod: '3.25.0' }, planned)).not.toThrow();
  });

  it('refuses a move of the required package the plan did not make', () => {
    // The lead alone was planned (zod already satisfied it): zod moving anyway is out of scope,
    // though npm and pnpm resolve it as the lead's peer.
    expect(() => guard({ openai: '7.4.0', zod: '3.25.0' }, 'openai')).toThrow(
      /outside openai's dependency subtree/,
    );
  });

  it('still refuses anything else that moves next to the planned moves', () => {
    expect(() => guard({ openai: '7.4.0', zod: '3.25.0', other: '1.1.0' }, planned)).toThrow(
      /outside openai, zod's dependency subtree/,
    );
  });
});
