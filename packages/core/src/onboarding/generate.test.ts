const generate = (snapshot: RepoSnapshot): Onboarding => generateOnboarding(repoFacts(snapshot));
const file = (o: Onboarding, path: string): string =>
  o.files.find((f) => f.path === path)?.content as string;

describe('golden files', () => {
  for (const [name, snapshot] of Object.entries(CASES))
    it(name, async () => {
      const o = generate(snapshot);
      expect(o.files.map((f) => f.path)).toEqual(['.github/workflows/uptide.yml', 'uptide.yml']);
      expect(o.prTitle).toBe('Add Uptide');
      await expect(file(o, '.github/workflows/uptide.yml')).toMatchFileSnapshot(
        `__golden__/${name}/workflow.yml`,
      );
      await expect(file(o, 'uptide.yml')).toMatchFileSnapshot(`__golden__/${name}/uptide.yml`);
      await expect(o.prBody).toMatchFileSnapshot(`__golden__/${name}/pr-body.md`);
    });
  // schedule: manual: the same repository as `npm`, with no scheduled runs.
  it('manual', async () => {
    const o = generateOnboarding(repoFacts(CASES.npm as RepoSnapshot), {
      config: { version: 1, schedule: 'manual' },
    });
    await expect(file(o, '.github/workflows/uptide.yml')).toMatchFileSnapshot(
      '__golden__/manual/workflow.yml',
    );
    await expect(file(o, 'uptide.yml')).toMatchFileSnapshot('__golden__/manual/uptide.yml');
    await expect(o.prBody).toMatchFileSnapshot('__golden__/manual/pr-body.md');
  });
  // minReleaseAgeDays set: the same repository as `npm`; only uptide.yml changes.
  it('release-age', async () => {
    const o = generateOnboarding(repoFacts(CASES.npm as RepoSnapshot), {
      config: { version: 1, minReleaseAgeDays: 7 },
    });
    await expect(file(o, 'uptide.yml')).toMatchFileSnapshot('__golden__/release-age/uptide.yml');
    expect(file(o, '.github/workflows/uptide.yml')).toBe(
      file(generate(CASES.npm as RepoSnapshot), '.github/workflows/uptide.yml'),
    );
  });
});

describe('schedule: manual', () => {
  const o = generateOnboarding(repoFacts(CASES.npm as RepoSnapshot), {
    config: { version: 1, schedule: 'manual' },
  });

  it('has only workflow_dispatch, no schedule trigger', () => {
    const workflow = parse(file(o, '.github/workflows/uptide.yml'));
    expect(Object.keys(workflow.on)).toEqual(['workflow_dispatch']);
    expect(file(o, '.github/workflows/uptide.yml')).not.toContain('cron:');
  });

  it('says in uptide.yml where runs start, and loads back as manual', () => {
    const text = file(o, 'uptide.yml');
    expect(text).toContain('Runs start from the Uptide\n# dashboard (Run now) or the Actions tab');
    expect(parseUptideConfig(text).config.schedule).toBe('manual');
  });

  it('says in the pull request that nothing runs on a schedule', () => {
    expect(o.prBody).toContain('The workflow has no schedule (`schedule: manual`)');
  });
});

describe('the workflow', () => {
  for (const [name, snapshot] of Object.entries(CASES))
    it(`${name}: parses, pins every action to a commit, and asks for the least it needs`, () => {
      const o = generate(snapshot);
      const workflow = parse(file(o, '.github/workflows/uptide.yml'));
      expect(Object.keys(workflow.on)).toEqual(['schedule', 'workflow_dispatch']);
      expect(workflow.on.schedule).toEqual([{ cron: o.config.schedule }]);
      expect(Object.keys(workflow.on.workflow_dispatch.inputs)).toEqual(['mode', 'package']);
      expect(workflow.on.workflow_dispatch.inputs.mode.options).toEqual(['list', 'check', 'fix']);
      // Read-only plus an identity: the Uptide Action pushes with the App's installation token,
      // so its pull requests run the repository's CI (GITHUB_TOKEN's would not).
      expect(workflow.permissions).toEqual({ contents: 'read', 'id-token': 'write' });
      // A pinned runner image: ubuntu-latest changes release under the repository's install.
      expect(workflow.jobs.uptide['runs-on']).toBe('ubuntu-24.04');
      expect(file(o, '.github/workflows/uptide.yml')).not.toContain('ubuntu-latest');
      const steps = workflow.jobs.uptide.steps as {
        uses?: string;
        run?: string;
        with?: Record<string, string>;
      }[];
      const uses = steps.flatMap((s) => (s.uses ? [s.uses] : []));
      expect(uses.length).toBeGreaterThanOrEqual(3);
      for (const ref of uses) expect(ref).toMatch(/^[\w.-]+\/[\w.-]+@[0-9a-f]{40}$/);
      // The repository is checked out without a token left in .git/config.
      expect(steps[0]?.with?.['persist-credentials']).toBe(false);
      // The key reaches the Uptide step alone; no shell line interpolates an expression.
      const uptide = steps.at(-1);
      expect(uptide?.uses).toBe(`${UPTIDE_ACTION.repo}@${UPTIDE_ACTION.sha}`);
      expect(Object.keys(uptide?.with ?? {})).toEqual([
        'config',
        'mode',
        'package',
        'anthropic-api-key',
      ]);
      expect(uptide?.with?.['anthropic-api-key']).toBe('${{ secrets.ANTHROPIC_API_KEY }}');
      expect(JSON.stringify(steps.slice(0, -1))).not.toContain('secrets.');
      for (const step of steps) expect(step.run ?? '').not.toContain('${{');
      // Installs run no dependency's lifecycle scripts.
      const install = steps.find(
        (s) => s.run && /\b(npm ci|install)\b/.test(s.run) && !/corepack/.test(s.run),
      );
      expect(install?.run).toMatch(/--ignore-scripts|--mode=skip-build/);
    });

  it('uses only the pinned actions it declares', () => {
    const known = new Set(
      [...Object.values(PINNED_ACTIONS), UPTIDE_ACTION].map((a) => `${a.repo}@${a.sha}`),
    );
    for (const snapshot of Object.values(CASES)) {
      const steps = parse(file(generate(snapshot), '.github/workflows/uptide.yml')).jobs.uptide
        .steps;
      for (const step of steps) if (step.uses) expect(known.has(step.uses), step.uses).toBe(true);
    }
  });

  it('runs a declared packageManager through Corepack, before setup-node caches with it', () => {
    const steps = parse(file(generate(CASES.pnpm as RepoSnapshot), '.github/workflows/uptide.yml'))
      .jobs.uptide.steps;
    const names = steps.map(
      (s: { uses?: string; name?: string }) => s.uses?.split('@')[0] ?? s.name,
    );
    expect(names).toEqual([
      'actions/checkout',
      'actions/setup-node',
      'Enable Corepack for pnpm@10.17.1+sha512.abcdef0123',
      'actions/setup-node',
      'Install dependencies',
      'uptide-dev/uptide',
    ]);
    expect(steps[1].with).toEqual({ 'node-version-file': '.nvmrc' });
    expect(steps[3].with).toEqual({ 'node-version-file': '.nvmrc', cache: 'pnpm' });
  });

  it('always passes the key, and offers no switch to turn the LLM off', () => {
    for (const snapshot of Object.values(CASES)) {
      const o = generate(snapshot);
      expect(file(o, '.github/workflows/uptide.yml')).toContain(
        'anthropic-api-key: ${{ secrets.ANTHROPIC_API_KEY }}',
      );
      expect(file(o, 'uptide.yml')).not.toMatch(/enabled/);
    }
  });
});

describe('uptide.yml as generated', () => {
  it.each([true, false])('preserves updatePins: %s through regeneration', (updatePins) => {
    const output = generateOnboarding(repoFacts(CASES.npm as RepoSnapshot), {
      config: { version: 1, updatePins },
    });
    expect(parseUptideConfig(file(output, 'uptide.yml')).config.updatePins).toBe(updatePins);
  });

  it('loads back to the settings it was written from, with a comment above every setting', () => {
    for (const snapshot of Object.values(CASES)) {
      const o = generate(snapshot);
      const text = file(o, 'uptide.yml');
      expect(parseUptideConfig(text).config).toEqual(o.config);
      const lines = text.split('\n');
      lines.forEach((line, i) => {
        if (/^\s*[a-zA-Z]+:/.test(line) && !/^(packages|llm):/.test(line))
          expect(lines[i - 1], line).toMatch(/^\s*#/);
      });
    }
  });

  it('writes minReleaseAgeDays only when set, 0 included, and loads it back', () => {
    expect(file(generate(CASES.npm as RepoSnapshot), 'uptide.yml')).not.toMatch(/minReleaseAge/);
    for (const days of [0, 7, 365]) {
      const o = generateOnboarding(repoFacts(CASES.npm as RepoSnapshot), {
        config: { version: 1, minReleaseAgeDays: days },
      });
      const text = file(o, 'uptide.yml');
      expect(text).toContain(`\nminReleaseAgeDays: ${days}\n`);
      expect(parseUptideConfig(text).config).toEqual(o.config);
      expect(o.config.minReleaseAgeDays).toBe(days);
    }
  });

  it('keeps an existing schedule and settings', () => {
    const o = generateOnboarding(repoFacts(CASES.npm as RepoSnapshot), {
      config: {
        version: 1,
        schedule: '11 22 * * 3',
        maxOpenPrs: 1,
        packages: { deny: ['stripe'] },
      },
    });
    expect(o.config).toMatchObject({ schedule: '11 22 * * 3', maxOpenPrs: 1 });
    expect(file(o, '.github/workflows/uptide.yml')).toContain("- cron: '11 22 * * 3'");
    expect(file(o, 'uptide.yml')).toContain("deny:\n    - 'stripe'");
  });
});

describe('the pull request', () => {
  const texts = Object.values(CASES).flatMap((s) => {
    const o = generate(s);
    return [o.prBody, ...o.files.map((f) => f.content)];
  });

  it('covers what runs, when, where, what leaves the runner, the required secret and removal', () => {
    const body = generate(CASES.npm as RepoSnapshot).prBody;
    for (const heading of [
      '## What runs, and when',
      '## Where it runs',
      '## What leaves the runner',
      '## Set the API key',
      '## Remove Uptide',
    ])
      expect(body).toContain(heading);
    expect(body).not.toContain('## Turn the LLM off');
    expect(body).not.toMatch(/enabled: false|rule-based fixes only/);
    expect(body).toContain('Without the secret, the workflow does not run Uptide');
    expect(body).toContain('every Monday at');
    expect(body).toContain('gh secret set ANTHROPIC_API_KEY');
    // Every place the runner talks to, and what the report never holds.
    expect(body).toContain('It never contains source code, diffs or environment values.');
    expect(body).toContain('(https://uptide-app.vercel.app/trust)');
    expect(body).toContain('**The npm registry**');
    expect(body).toContain('**GitHub**');
    expect(body).not.toContain('Nothing else leaves the runner');
  });

  it('says what goes to an LLM as the Action does it: the SDK reads any file', () => {
    const body = (config: Omit<UptideConfigInput, 'version'> = {}) =>
      generateOnboarding(repoFacts(CASES.npm as RepoSnapshot), {
        config: { version: 1, ...config },
      }).prBody;
    // The Agent SDK is the only executor, and it can read the whole checkout. An older
    // `executor: patch` is not carried into the generated uptide.yml.
    for (const config of [{}, { executor: 'patch' as const }]) {
      const o = generateOnboarding(repoFacts(CASES.npm as RepoSnapshot), {
        config: { version: 1, ...config },
      });
      expect(o.prBody).toContain('can read any file in the checkout');
      expect(o.files.find((f) => f.path === 'uptide.yml')?.content).not.toContain('executor');
    }
    // The workflow passes only an Anthropic key: the generator refuses another provider.
    expect(() => body({ llm: { provider: 'openai' } })).toThrow(/passes only an Anthropic key/);
  });

  it('is plain English: no em or en dashes, no hype words', () => {
    for (const text of texts) {
      expect(text).not.toMatch(/[–—]/);
      expect(text).not.toMatch(
        /\b(seamless(ly)?|effortless(ly)?|powerful|revolutionary|magic(al)?|blazing|supercharge|game-changing|cutting-edge|unleash|robust|leverage)\b/i,
      );
    }
  });
});

describe('purity', () => {
  it('gives the same bytes for the same facts and never changes them', () => {
    const facts = Object.freeze(repoFacts(CASES.monorepo as RepoSnapshot));
    expect(generateOnboarding(facts)).toEqual(generateOnboarding(structuredClone(facts)));
  });

  it('reads no file system, network, process or clock in the generator', () => {
    for (const source of [
      'facts.ts',
      'generate.ts',
      'render.ts',
      'cron.ts',
      'actions.ts',
      'schema.ts',
      'validate.ts',
    ]) {
      const text = readFileSync(new URL(source, import.meta.url), 'utf8');
      expect(text, source).not.toMatch(/from 'node:|fetch\(|process\.|Date\.now|new Date\(/);
    }
  });
});

describe('refusals', () => {
  const refusal = (
    files: RepoSnapshot['files'],
    config?: Parameters<typeof generateOnboarding>[1],
  ) => {
    try {
      generateOnboarding(repoFacts({ defaultBranch: 'main', files }), config);
    } catch (err) {
      expect(err).toBeInstanceOf(OnboardingRefusal);
      return err as OnboardingRefusal;
    }
    throw new Error('expected a refusal');
  };
  const cases: [string, RefusalReason, RepoSnapshot['files'], string][] = [
    [
      'a repository without package.json',
      'not-javascript',
      { 'go.mod': 'module x' } as RepoSnapshot['files'],
      'no package.json at the repository root',
    ],
    [
      'an invalid package.json',
      'invalid-manifest',
      { 'package.json': '{', 'package-lock.json': npmLock },
      'not valid JSON',
    ],
    [
      'a Bun lockfile',
      'bun',
      { 'package.json': manifest(), 'bun.lockb': '' },
      'Bun is not supported',
    ],
    [
      'a text Bun lockfile',
      'bun',
      { 'package.json': manifest(), 'bun.lock': '{}' },
      'Bun is not supported',
    ],
    [
      'packageManager bun',
      'bun',
      { 'package.json': manifest({ packageManager: 'bun@1.2.0' }), 'package-lock.json': npmLock },
      'packageManager is bun@1.2.0',
    ],
    ['no lockfile', 'no-lockfile', { 'package.json': manifest() }, 'There is no lockfile'],
    [
      'packageManager pnpm with an npm lockfile',
      'manager-mismatch',
      { 'package.json': manifest({ packageManager: 'pnpm@9.15.0' }), 'package-lock.json': npmLock },
      'packageManager pnpm@9.15.0, but the lockfile is package-lock.json',
    ],
    [
      'packageManager yarn 4 with a classic yarn.lock',
      'manager-mismatch',
      {
        'package.json': manifest({ packageManager: 'yarn@4.9.2' }),
        'yarn.lock': classicLock,
        '.yarnrc.yml': 'nodeLinker: node-modules\n',
      },
      'Yarn classic (1) format',
    ],
    [
      'packageManager yarn 1 with a Berry yarn.lock',
      'manager-mismatch',
      { 'package.json': manifest({ packageManager: 'yarn@1.22.22' }), 'yarn.lock': berryLock },
      'Yarn Berry (2 or newer) format',
    ],
    [
      'packageManager pnpm 8 with a pnpm 9 lockfile',
      'manager-mismatch',
      { 'package.json': manifest({ packageManager: 'pnpm@8.15.9' }), 'pnpm-lock.yaml': pnpmLock },
      'written by pnpm 9 or newer',
    ],
    [
      'a malformed packageManager',
      'invalid-manifest',
      { 'package.json': manifest({ packageManager: 'pnpm' }), 'pnpm-lock.yaml': pnpmLock },
      'name@version',
    ],
    [
      'two lockfiles and no packageManager',
      'several-lockfiles',
      { 'package.json': manifest(), 'package-lock.json': npmLock, 'yarn.lock': classicLock },
      'several lockfiles (package-lock.json, yarn.lock)',
    ],
    [
      'an npm lockfile v1',
      'unsupported-lockfile',
      { 'package.json': manifest(), 'package-lock.json': '{"lockfileVersion": 1}' },
      'lockfileVersion 1',
    ],
    [
      'an old pnpm lockfile without packageManager',
      'unknown-manager-version',
      { 'package.json': manifest(), 'pnpm-lock.yaml': 'lockfileVersion: 5.3\n' },
      'Set "packageManager"',
    ],
    [
      'Yarn Berry with no version anywhere',
      'unknown-manager-version',
      {
        'package.json': manifest(),
        'yarn.lock': berryLock,
        '.yarnrc.yml': 'nodeLinker: node-modules\n',
      },
      'which Yarn to run',
    ],
    [
      'Yarn Plug and Play',
      'yarn-pnp',
      { 'package.json': manifest({ packageManager: 'yarn@4.9.2' }), 'yarn.lock': berryLock },
      "Plug'n'Play",
    ],
    [
      'an engines.node no supported Node meets',
      'unsupported-node',
      { 'package.json': manifest({ engines: { node: '14.x' } }), 'package-lock.json': npmLock },
      'engines.node is "14.x"',
    ],
  ];
  for (const [what, reason, files, message] of cases)
    it(`refuses ${what}`, () => {
      const err = refusal(files);
      expect(err.reason).toBe(reason);
      expect(err.code).toBe('ONBOARDING_REFUSED');
      expect(err.message).toContain(message);
    });

  it('refuses a provider the workflow cannot pass a key for', () => {
    const err = refusal(CASES.npm?.files as RepoSnapshot['files'], {
      config: { version: 1, llm: { provider: 'openai' } },
    });
    expect(err.reason).toBe('unsupported-provider');
    expect(err.message).toContain('ANTHROPIC_API_KEY');
  });

  it('refuses an existing uptide.yml that turns the LLM off, which the Action rejects', () => {
    const err = refusal(CASES.npm?.files as RepoSnapshot['files'], {
      config: { version: 1, llm: { enabled: false } },
    });
    expect(err.reason).toBe('llm-disabled');
    expect(err.message).toContain('Remove llm.enabled from uptide.yml');
    // An older file that says true still generates: true is what the Action does anyway.
    const o = generateOnboarding(repoFacts(CASES.npm as RepoSnapshot), {
      config: { version: 1, llm: { enabled: true } },
    });
    expect(file(o, 'uptide.yml')).not.toMatch(/enabled/);
  });

  it('chooses the lockfile packageManager names when there are several', () => {
    const facts = repoFacts({
      defaultBranch: 'main',
      files: {
        'package.json': manifest({ packageManager: 'pnpm@10.17.1' }),
        'pnpm-lock.yaml': pnpmLock,
        'package-lock.json': npmLock,
      },
    });
    expect(facts.manager.lockfile).toBe('pnpm-lock.yaml');
  });
});
